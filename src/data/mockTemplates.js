export const templateStore = [
  defaultTemplate,
  cryptoTemplate,
  securityTemplate,
];

export function resolveTemplate(prompt = "") {
  const normalized = prompt.toLowerCase();

  if (
    normalized.includes("crypto") ||
    normalized.includes("bitcoin") ||
    normalized.includes("ethereum") ||
    normalized.includes("trading") ||
    normalized.includes("portfolio")
  ) {
    return cryptoTemplate;
  }

  if (
    normalized.includes("security") ||
    normalized.includes("cyber") ||
    normalized.includes("soc") ||
    normalized.includes("threat") ||
    normalized.includes("incident") ||
    normalized.includes("zero trust")
  ) {
    return securityTemplate;
  }

  return null;
}

export default templateStore;
